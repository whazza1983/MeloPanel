const LANG_KEY = 'nd_lang';

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'de' || saved === 'en') return saved;
  } catch (e) { /* storage not available */ }
  return (navigator.language || '').toLowerCase().startsWith('de') ? 'de' : 'en';
}

let LANG = detectLang();
document.documentElement.lang = LANG;

function setLang(lang) {
  LANG = lang === 'de' ? 'de' : 'en';
  document.documentElement.lang = LANG;
  try { localStorage.setItem(LANG_KEY, LANG); } catch (e) { /* ignore */ }
}

// Translate: t('key', {name: 'x'}); for [singular, plural], vars.n decides
function t(key, vars = {}) {
  let text = (I18N[LANG] && I18N[LANG][key]) ?? I18N.de[key] ?? key;
  if (Array.isArray(text)) text = Number(vars.n) === 1 ? text[0] : text[1];
  return text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
}

// Static texts in HTML: data-i18n (text), data-i18n-title, data-i18n-placeholder, data-i18n-aria
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-lang-btn]').forEach((el) => el.classList.toggle('active', el.dataset.langBtn === LANG));
}
